#!/usr/bin/env python3
"""Restart / rollback / status of a k8s deployment THROUGH Jenkins.

Why: our own k8s credentials are read-only on most clusters, but each build job
already holds a kubeconfig credential that can scale / set image. Instead of
hand-editing the build pipeline, we create ONE companion job `<job>-ops` next
to it (same folder, same agent, same kubeconfig credential) with parameters
ACTION=status|restart|rollback and TAG. The build job is never touched.

Everything is rendered from the registry (work/projects.json, merged with
work/platforms.json), block `environments.<env>.jenkins`:
    job            "job/<folder>/.../job/<name>"   build job (ops job = <name>-ops beside it)
    agent          Jenkins agent label the build job uses
    k8s_credential Jenkins file credential id holding the kubeconfig
    resource       "deployment/<name>"
    container      container name in that deployment
    namespace      k8s namespace
    image          image repository without tag
    git_tag_prefix prefix of the git tags the build job pushes (e.g. "prod-econ.")
    branch         (optional) branch the build job builds; `tags` then marks which tags are on it
                   (sandbox and prod may share one tag prefix + image repo)

Usage:
    python jenkins_ops.py render --project etask --env sandbox          # print job XML (no network)
    python jenkins_ops.py create --project etask --env sandbox [--update] [--dry-run]   # [WRITE] Jenkins
    python jenkins_ops.py tags   --project etask --env sandbox [--limit 15]   # versions from git tags
    python jenkins_ops.py run    --project etask --env sandbox --action status|restart|rollback [--tag 1.2.3] [--wait] [--dry-run] [--via auto|ops|swap]

When the Jenkins user may not create jobs (createItem = 403) but may configure the
build job, `--via swap` (and `auto` when the ops job does not exist) does what people
did by hand: back up the build job's config.xml (work/jenkins/backups/), replace ONLY
its <script> with the ops script (parameters baked in), run it once, then ALWAYS post
the original back and verify the script matches. Refused while the build job is
queued/running.

Restart/rollback mirror the build job's own deploy steps (scale 0 -> [set image] ->
scale back to the previous replica count -> rollout status) so they only need the
permissions the build job already uses. Protected envs (prod) are refused unless
--allow-prod. Output: one JSON object.
"""

import argparse
import json
import os
import re
import subprocess
import sys
import time
import urllib.parse
from xml.sax.saxutils import escape

import jenkins
import probe_common as pc
import project_config

ACTIONS = ("status", "restart", "rollback")
TAG_RE = re.compile(r"^\d+\.\d+\.\d+$")
REQUIRED = ("job", "agent", "k8s_credential", "resource", "container", "namespace", "image")
# Values are pasted into a Groovy single-quoted string: allow only harmless characters.
SAFE_RE = re.compile(r"^[A-Za-z0-9._/:@-]+$")

SCRIPT = """\
// Generated by Agent-Skill-Toolkit jenkins_ops.py - do not edit by hand; re-run `jenkins_ops.py create --update`.
pipeline {
  agent { label '@AGENT@' }
  options { disableConcurrentBuilds(); timeout(time: 20, unit: 'MINUTES') }
  environment {
    K8S_CONFIG = credentials('@CRED@')
    NS = '@NS@'
    RES = '@RES@'
    CONTAINER = '@CONTAINER@'
    IMAGE = '@IMAGE@'
  }
  stages {
    stage('Status before') {
      steps {
        sh 'kubectl --kubeconfig=$K8S_CONFIG -n $NS get $RES -o jsonpath="image={.spec.template.spec.containers[*].image} replicas={.spec.replicas} ready={.status.readyReplicas}"; echo'
      }
    }
    stage('Restart') {
      when { expression { params.ACTION == 'restart' } }
      steps {
        sh '''
          set -e
          N=$(kubectl --kubeconfig=$K8S_CONFIG -n $NS get $RES -o jsonpath="{.spec.replicas}")
          [ -n "$N" ] && [ "$N" -gt 0 ] || N=1
          echo "restart: scale 0 -> $N"
          kubectl --kubeconfig=$K8S_CONFIG -n $NS scale $RES --replicas 0
          sleep 10
          kubectl --kubeconfig=$K8S_CONFIG -n $NS scale $RES --replicas $N
          kubectl --kubeconfig=$K8S_CONFIG -n $NS rollout status $RES --timeout=900s
        '''
      }
    }
    stage('Rollback') {
      when { expression { params.ACTION == 'rollback' } }
      steps {
        script {
          if (!(params.TAG ==~ /^[0-9]+[.][0-9]+[.][0-9]+$/)) { error "TAG must look like 1.2.3, got: ${params.TAG}" }
        }
        sh '''
          set -e
          N=$(kubectl --kubeconfig=$K8S_CONFIG -n $NS get $RES -o jsonpath="{.spec.replicas}")
          [ -n "$N" ] && [ "$N" -gt 0 ] || N=1
          echo "rollback: $CONTAINER -> $IMAGE:$TAG (replicas $N)"
          kubectl --kubeconfig=$K8S_CONFIG -n $NS scale $RES --replicas 0
          kubectl --kubeconfig=$K8S_CONFIG -n $NS set image $RES $CONTAINER=$IMAGE:$TAG
          sleep 10
          kubectl --kubeconfig=$K8S_CONFIG -n $NS scale $RES --replicas $N
          kubectl --kubeconfig=$K8S_CONFIG -n $NS rollout status $RES --timeout=900s
        '''
      }
    }
    stage('Status after') {
      when { expression { params.ACTION != 'status' } }
      steps {
        sh 'kubectl --kubeconfig=$K8S_CONFIG -n $NS get $RES -o jsonpath="image={.spec.template.spec.containers[*].image} replicas={.spec.replicas} ready={.status.readyReplicas}"; echo'
      }
    }
  }
}
"""

XML = """<?xml version='1.1' encoding='UTF-8'?>
<flow-definition plugin="workflow-job">
  <description>{desc}</description>
  <keepDependencies>false</keepDependencies>
  <properties>
    <hudson.model.ParametersDefinitionProperty>
      <parameterDefinitions>
        <hudson.model.ChoiceParameterDefinition>
          <name>ACTION</name>
          <description>status = chỉ xem · restart = scale 0 rồi scale lại · rollback = đổi image sang TAG</description>
          <choices class="java.util.Arrays$ArrayList">
            <a class="string-array"><string>status</string><string>restart</string><string>rollback</string></a>
          </choices>
        </hudson.model.ChoiceParameterDefinition>
        <hudson.model.StringParameterDefinition>
          <name>TAG</name>
          <description>Chỉ dùng cho rollback: tag image dạng 1.2.3</description>
          <defaultValue></defaultValue>
          <trim>true</trim>
        </hudson.model.StringParameterDefinition>
      </parameterDefinitions>
    </hudson.model.ParametersDefinitionProperty>
  </properties>
  <definition class="org.jenkinsci.plugins.workflow.cps.CpsFlowDefinition" plugin="workflow-cps">
    <script>{script}</script>
    <sandbox>true</sandbox>
  </definition>
  <triggers/>
  <disabled>false</disabled>
</flow-definition>
"""


SWAP_MARK = "// jenkins_ops SWAP: temporary ops script; the original pipeline is restored automatically"
SCRIPT_RE = re.compile(r"(<script>)(.*?)(</script>)", re.S)


class OpsError(Exception):
    pass


def ops_spec(stack: dict) -> dict:
    """Validate the registry jenkins block and derive the ops job paths."""
    j = dict(stack.get("jenkins") or {})
    missing = [k for k in REQUIRED if not j.get(k)]
    if missing:
        raise OpsError(f"registry jenkins block is missing: {', '.join(missing)}")
    for k in REQUIRED[1:]:
        if not SAFE_RE.match(str(j[k])):
            raise OpsError(f"unsafe characters in jenkins.{k}: {j[k]!r}")
    job = j["job"].strip("/")
    folder, _, name = job.rpartition("/job/")
    if not folder or not name:
        raise OpsError(f"jenkins.job must be a folder path like job/a/job/b, got {job!r}")
    j["folder"] = folder
    j["ops_name"] = j.get("ops_name") or f"{name}-ops"
    j["ops_job"] = f"{folder}/job/{j['ops_name']}"
    return j


def render_script(spec: dict, action: str = "", tag: str = "") -> str:
    """Ops pipeline. With `action`, parameters are baked in as literals (swap mode:
    the build job has no ACTION/TAG parameters)."""
    script = (SCRIPT.replace("@AGENT@", spec["agent"]).replace("@CRED@", spec["k8s_credential"])
              .replace("@NS@", spec["namespace"]).replace("@RES@", spec["resource"])
              .replace("@CONTAINER@", spec["container"]).replace("@IMAGE@", spec["image"]))
    if action:
        if action not in ACTIONS or (tag and not TAG_RE.match(tag)):
            raise OpsError(f"bad action/tag for swap: {action!r} {tag!r}")
        script = (script.replace("params.ACTION", f"'{action}'").replace("params.TAG", f"'{tag}'")
                  .replace("$IMAGE:$TAG", f"$IMAGE:{tag}"))
        script = SWAP_MARK + "\n" + script
    return script


def render_xml(spec: dict) -> str:
    script = render_script(spec)
    desc = (f"Restart/rollback {spec['resource']} ({spec['namespace']}) qua kubeconfig của job build. "
            f"Sinh bởi Agent-Skill-Toolkit jenkins_ops.py — sửa registry rồi chạy lại create --update.")
    return XML.format(desc=escape(desc), script=escape(script))


def list_tags(clone_dir: str, prefix: str, limit: int) -> list:
    """Versions from the git tags the build job pushes (newest first)."""
    if not clone_dir or not os.path.isdir(clone_dir):
        raise OpsError(f"clone_dir not found: {clone_dir!r}")
    out = subprocess.run(["git", "-C", clone_dir, "tag", "-l", f"{prefix}*"],
                         capture_output=True, text=True, encoding="utf-8", errors="replace", check=False).stdout.split()
    vers = [t[len(prefix):] for t in out if TAG_RE.match(t[len(prefix):])]
    vers.sort(key=lambda v: tuple(int(x) for x in v.split(".")), reverse=True)
    return vers[:limit]


def describe_tags(clone_dir: str, prefix: str, branch: str, limit: int) -> list:
    """list_tags + commit/date and, if a branch is given, whether the tag is on origin/<branch>."""
    rows = []
    for v in list_tags(clone_dir, prefix, limit):
        ref = f"{prefix}{v}^{{commit}}"
        info = subprocess.run(["git", "-C", clone_dir, "log", "-1", "--format=%h %cs %s", ref],
                              capture_output=True, text=True, encoding="utf-8", errors="replace", check=False).stdout.strip()
        sha, _, rest = info.partition(" ")
        date, _, subject = rest.partition(" ")
        row = {"tag": v, "commit": sha, "date": date, "subject": subject[:80]}
        if branch:
            rc = subprocess.run(["git", "-C", clone_dir, "merge-base", "--is-ancestor", ref, f"origin/{branch}"],
                                capture_output=True, check=False).returncode
            row["on_branch"] = rc == 0
        rows.append(row)
    return rows


def _post_xml(url: str, xml: str):
    headers = {"Content-Type": "application/xml; charset=utf-8", **jenkins._crumb_header()}
    return jenkins._req("POST", url, data=xml.encode("utf-8"), extra_headers=headers)


def cmd_create(spec: dict, args) -> dict:
    base = jenkins._base()
    xml = render_xml(spec)
    if args.update:
        url = f"{base}/{spec['ops_job']}/config.xml"
    else:
        url = f"{base}/{spec['folder']}/createItem?name={urllib.parse.quote(spec['ops_name'])}"
    if args.dry_run:
        return {"dry_run": True, "method": "POST", "url": url, "ops_job": spec["ops_job"], "bytes": len(xml)}
    status, _, body = _post_xml(url, xml)
    if status not in (200, 201, 302):
        hint = ""
        if status == 400 and "already exists" in body:
            hint = " — job already exists: use --update"
        elif status == 403:
            hint = " — this Jenkins user lacks Job/Create (or Configure) in that folder"
        return {"error": True, "passed": False, "status": status,
                "message": f"create failed: HTTP {status}{hint}", "body": body[:300]}
    return {"passed": True, "ops_job": spec["ops_job"], "url": f"{base}/{spec['ops_job']}/",
            "updated": bool(args.update)}


def _validate_run(spec: dict, args, tags_fn) -> None:
    if args.action == "rollback":
        if not args.tag or not TAG_RE.match(args.tag):
            raise OpsError("rollback needs --tag x.y.z (see `jenkins_ops.py tags`)")
        known = tags_fn(args._clone_dir, spec.get("git_tag_prefix", ""), 1000) if spec.get("git_tag_prefix") else []
        if known and args.tag not in known:
            raise OpsError(f"tag {args.tag} not found among {spec['git_tag_prefix']}* git tags (fetch the clone?)")
    elif args.tag:
        raise OpsError("--tag is only for --action rollback")


def ops_job_exists(spec: dict) -> bool:
    status, _, _ = jenkins._req("GET", f"{jenkins._base()}/{spec['ops_job']}/api/json?tree=name")
    return status == 200


def cmd_run(spec: dict, args, tags_fn=list_tags) -> dict:
    _validate_run(spec, args, tags_fn)
    via = getattr(args, "via", "ops")
    if via == "auto":
        via = "ops" if ops_job_exists(spec) else "swap"
    if via == "swap":
        return swap_run(spec, args)
    ns = argparse.Namespace(path=spec["ops_job"], job=None, dry_run=args.dry_run, wait=args.wait,
                            timeout=args.timeout, poll=5,
                            param=[f"ACTION={args.action}", f"TAG={args.tag or ''}"])
    out = jenkins.cmd_build(ns)
    out["ops_job"] = spec["ops_job"]
    out["via"] = "ops"
    return out


def swap_xml(original: str, script: str) -> str:
    """Original job config with ONLY the <script> body replaced (everything else byte-identical)."""
    if len(SCRIPT_RE.findall(original)) != 1:
        raise OpsError("build job config has no single inline <script> (Jenkinsfile from SCM?) - swap mode cannot work")
    return SCRIPT_RE.sub(lambda m: m.group(1) + escape(script) + m.group(3), original, count=1)


def _script_of(xml: str) -> str:
    m = SCRIPT_RE.search(xml)
    return m.group(2) if m else ""


def _backup_path(args) -> str:
    d = os.path.join(project_config._work_dir(), "jenkins", "backups")
    os.makedirs(d, exist_ok=True)
    return os.path.join(d, f"{args.project}-{args.env}-{time.strftime('%Y%m%d-%H%M%S')}.config.xml")


def swap_run(spec: dict, args) -> dict:
    """Temporarily replace the build job's pipeline with the ops script, run it once,
    and ALWAYS restore the original config (verified). The user's manual workaround, automated."""
    base, job = jenkins._base(), spec["job"]
    script = render_script(spec, args.action, args.tag or "")
    steps = ["check build job idle", "GET config.xml -> backup", "POST config.xml (ops script)",
             "build + wait", "POST original config.xml", "verify restored"]
    if args.dry_run:
        return {"dry_run": True, "via": "swap", "job": job, "action": args.action, "tag": args.tag, "steps": steps}

    st, _, body = jenkins._req("GET", f"{base}/{job}/api/json?tree=inQueue,lastBuild[number,building]")
    if st != 200:
        raise OpsError(f"cannot read build job state: HTTP {st}")
    state = json.loads(body)
    if state.get("inQueue") or (state.get("lastBuild") or {}).get("building"):
        raise OpsError("build job is queued/running - refusing to swap its pipeline now; retry later")

    st, _, original = jenkins._req("GET", f"{base}/{job}/config.xml")
    if st != 200 or "<flow-definition" not in original:
        raise OpsError(f"cannot read build job config.xml: HTTP {st}")
    backup = _backup_path(args)
    with open(backup, "w", encoding="utf-8") as f:
        f.write(original)
    swapped = swap_xml(original, script)

    out = {"via": "swap", "job": job, "action": args.action, "tag": args.tag, "backup": backup}
    try:
        st, _, body = _post_xml(f"{base}/{job}/config.xml", swapped)
        if st not in (200, 302):
            raise OpsError(f"could not install ops script: HTTP {st} {body[:200]}")
        ns = argparse.Namespace(path=job, job=None, dry_run=False, wait=True,
                                timeout=args.timeout, poll=5, param=None)
        out.update(jenkins.cmd_build(ns))
    finally:
        out["restore"] = restore_config(job, original)
    if not out["restore"].get("ok"):
        out.update(error=True, passed=False,
                   message=f"ORIGINAL PIPELINE NOT RESTORED - restore by hand from {backup}")
    return out


def restore_config(job: str, original: str) -> dict:
    base = jenkins._base()
    last = ""
    for _ in range(3):
        st, _, body = _post_xml(f"{base}/{job}/config.xml", original)
        if st in (200, 302):
            st2, _, now = jenkins._req("GET", f"{base}/{job}/config.xml")
            if st2 == 200 and _script_of(now) == _script_of(original):
                return {"ok": True}
            last = f"verify mismatch (HTTP {st2})"
        else:
            last = f"HTTP {st} {body[:200]}"
        time.sleep(2)
    return {"ok": False, "detail": last}


def main() -> int:
    p = argparse.ArgumentParser(description="k8s restart/rollback via a Jenkins ops job")
    sub = p.add_subparsers(dest="cmd", required=True)
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--project", required=True)
    common.add_argument("--env", required=True)
    common.add_argument("--allow-prod", action="store_true")
    sub.add_parser("render", parents=[common])
    c = sub.add_parser("create", parents=[common])
    c.add_argument("--update", action="store_true", help="overwrite the existing ops job config")
    c.add_argument("--dry-run", action="store_true")
    t = sub.add_parser("tags", parents=[common])
    t.add_argument("--limit", type=int, default=15)
    r = sub.add_parser("run", parents=[common])
    r.add_argument("--action", choices=ACTIONS, required=True)
    r.add_argument("--tag")
    r.add_argument("--wait", action="store_true")
    r.add_argument("--timeout", type=int, default=1500)
    r.add_argument("--dry-run", action="store_true")
    r.add_argument("--via", choices=("auto", "ops", "swap"), default="auto",
                   help="ops = companion job; swap = temporarily replace the build job pipeline and restore it; "
                        "auto = ops if it exists, else swap")
    args = p.parse_args()

    mutating = args.cmd in ("create", "run")
    err = project_config.apply_args(args, mutating=mutating)
    if err:
        return pc.emit(err)
    try:
        spec = ops_spec(args._ctx["stack"])
        args._clone_dir = project_config.load(args.project).get("clone_dir", "")
        if args.cmd == "render":
            sys.stdout.buffer.write(render_xml(spec).encode("utf-8"))
            return 0
        if args.cmd == "create":
            out = cmd_create(spec, args)
        elif args.cmd == "tags":
            out = {"passed": True, "prefix": spec.get("git_tag_prefix", ""), "branch": spec.get("branch", ""),
                   "tags": describe_tags(args._clone_dir, spec.get("git_tag_prefix", ""),
                                         spec.get("branch", ""), args.limit)}
        else:
            out = cmd_run(spec, args)
    except (OpsError, ValueError) as e:
        out = {"error": True, "passed": False, "message": str(e)}
    return pc.emit(out)


if __name__ == "__main__":
    sys.exit(main())
